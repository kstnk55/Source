/*@brief      TransitionToFBL
 * @pre        -
 * @param[in]  -
 * @param[out] -
 * @return     -
 * @context    - Handling jump to address FBL
 *****************************************************************************/
void TransitionToFBL(void)
{
  if (RESET_COUNTER < RESET_COUNTER_LIMIT + 1)
  {
  /* Do nothing */
  }
  else if (RESET_COUNTER == RESET_COUNTER_LIMIT + 1)
  {
    /* Reset CM7_0*/
    CM7_0_PWR_CTL = 0x05FA0001UL;
    /* Reset CM7_1*/
    CM7_1_PWR_CTL = 0x05FA0001UL;
    /* Set vector to FBL*/
    CM7_0_VECTOR_TABLE_BASE = 0x103F8000UL;
    /* Start CM7_0*/
    CM7_0_PWR_CTL = 0x05FA0003UL;
    /*Wait signal */
    CM7_0_CTL &= ~(0x10UL);
  }
  else
  {
  RESET_COUNTER = 0UL;
  }
} 
